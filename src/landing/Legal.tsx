export function Legal({ page }: { page: 'privacy' | 'terms' }) {
  const sections = page === 'privacy' ? PRIVACY : TERMS;
  const title = page === 'privacy' ? 'حریم خصوصی' : 'شرایط استفاده';
  useEffect(() => {
    const prev = document.title;
    document.title = `${title} | بیومانا`;
    window.scrollTo(0, 0);
    return () => {
      document.title = prev;
    };
  }, [title]);
  return (
    <div className="fl-legal">
      <header className="fl-legal-top">
        <a href="/#/welcome" className="fl-logo">
          <BrandMark size={32} />
          <span>بیومانا</span>
        </a>
        <a href="/#/welcome" className="fl-btn line sm">
          <Icon name="back" size={16} /> بازگشت
        </a>
      </header>
      <main className="fl-legal-body">
        <h1>{title}</h1>
        {sections.map(([h, ps]) => (
          <section key={h}>
            <h2>{h}</h2>
            {ps.map((p) => (
              <p key={p}>{p}</p>
            ))}
          </section>
        ))}
        <p className="fl-legal-date">آخرین تغییر: ۲۹ مهر ۱۴۰۵</p>
        <nav className="fl-legal-nav">
          <a href={page === 'privacy' ? '/#/terms' : '/#/privacy'}>{page === 'privacy' ? 'شرایط استفاده' : 'حریم خصوصی'}</a>
        </nav>
      </main>
    </div>
  );
}
